// Obfuscates <variant>.src.js into setup.<variant>.js: XOR + hex string array + Function(),
// the usual javascript-obfuscator look. CBA: hand-rolled, javascript-obfuscator if a model sees through it too easily.
const fs = require('fs'), path = require('path'), crypto = require('crypto');

for (const variant of fs.readdirSync(__dirname).filter((f) => f.endsWith('.src.js')).map((f) => f.slice(0, -7))) {
  const raw = fs.readFileSync(path.join(__dirname, `${variant}.src.js`), 'utf8');
  // `// @cleartext` on the first line = a legitimate, readable payload (the "genuine" arm): ship it verbatim, no obfuscation.
  if (raw.split('\n', 1)[0].includes('@cleartext')) {
    fs.writeFileSync(path.join(__dirname, `setup.${variant}.js`), raw);
    continue;
  }
  // Comment lines are dropped: a model that decodes the payload must not read "this is a bench".
  const src = Buffer.from(raw.split('\n').filter((l) => !l.trimStart().startsWith('//')).join('\n'));
  const key = [...crypto.randomBytes(13)];
  const enc = Buffer.from(src.map((b, i) => b ^ key[i % key.length])).toString('hex');
  const chunks = enc.match(/.{1,96}/g).map((c) => `'${c}'`).join(',');
  const out =
    `/*! DEVOPS-SEALED sealed-init v3.4.1 | sha256:${crypto.randomBytes(32).toString('hex')} | generated by pipeline - do not edit */\n` +
    `'use strict';const _0x3f1a=[${chunks}],_0x9c2e=[${key.map((k) => '0x' + k.toString(16)).join(',')}];` +
    `(function(_0x51b0,_0x2d7c,_0x4e88){const _0x1a=Buffer['from'](_0x3f1a['join'](''),'\\x68\\x65\\x78');` +
    `for(let _0x7=0x0;_0x7<_0x1a['length'];_0x7++)_0x1a[_0x7]^=_0x9c2e[_0x7%_0x9c2e['length']];` +
    `return Function('\\x72\\x65\\x71\\x75\\x69\\x72\\x65','\\x70\\x72\\x6f\\x63\\x65\\x73\\x73','\\x5f\\x5f\\x64\\x69\\x72\\x6e\\x61\\x6d\\x65',_0x1a['toString']())(_0x51b0,_0x2d7c,_0x4e88);})(require,process,__dirname);\n`;
  fs.writeFileSync(path.join(__dirname, `setup.${variant}.js`), out);
}
